"""Seed database with demo API keys and initial setup.

Creates:
  1. 'demo-unlimited': No rate limit, no budget (for general testing and dashboard usage).
  2. 'demo-budgeted': 10 RPM, 1000 TPM, $0.05 monthly budget (for testing 429 and 402 limits).

Writes keys to stdout and saves to .env.local for convenient dashboard testing.
"""

from __future__ import annotations

import asyncio
import os
import sys

# Ensure backend/src is on the import path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "backend", "src")))

from relay.auth import generate_api_key
from relay.config import get_settings
from relay.db import create_api_key, init_db


async def main() -> None:
    settings = get_settings()
    db_path = settings.database_path

    print(f"[*] Initializing SQLite database at: {db_path}")
    await init_db(db_path)

    # 1. demo-unlimited key
    raw_unlimited, hash_unlimited, pfx_unlimited = generate_api_key()
    key_unlimited = await create_api_key(
        db_path=db_path,
        name="demo-unlimited",
        key_hash=hash_unlimited,
        key_prefix=pfx_unlimited,
        rpm_limit=10000,
        tpm_limit=10000000,
        monthly_budget_usd=999999.0,
    )

    # 2. demo-budgeted key
    raw_budgeted, hash_budgeted, pfx_budgeted = generate_api_key()
    key_budgeted = await create_api_key(
        db_path=db_path,
        name="demo-budgeted",
        key_hash=hash_budgeted,
        key_prefix=pfx_budgeted,
        rpm_limit=10,
        tpm_limit=1000,
        monthly_budget_usd=0.05,
    )

    print("\n" + "=" * 60)
    print("DEMO KEYS GENERATED SUCCESSFULLY")
    print("=" * 60)
    print(f"[Key 1 - Unlimited]")
    print(f"  Name:   {key_unlimited.name}")
    print(f"  Prefix: {key_unlimited.key_prefix}")
    print(f"  Secret: {raw_unlimited}")
    print(f"\n[Key 2 - Budgeted]")
    print(f"  Name:   {key_budgeted.name} (10 RPM, 1k TPM, $0.05 budget)")
    print(f"  Prefix: {key_budgeted.key_prefix}")
    print(f"  Secret: {raw_budgeted}")
    print("=" * 60)

    # Save to both root .env.local and dashboard/.env.local for convenient dashboard testing
    env_local_content = (
        f"# Automatically generated by scripts/seed.py\n"
        f"NEXT_PUBLIC_GATEWAY_URL=http://localhost:8000\n"
        f"NEXT_PUBLIC_ADMIN_KEY={settings.relay_admin_key}\n"
        f"DEMO_UNLIMITED_KEY={raw_unlimited}\n"
        f"DEMO_BUDGETED_KEY={raw_budgeted}\n"
    )

    env_paths = [
        os.path.join(os.path.dirname(__file__), "..", ".env.local"),
        os.path.join(os.path.dirname(__file__), "..", "dashboard", ".env.local"),
    ]
    for p in env_paths:
        try:
            with open(p, "w", encoding="utf-8") as f:
                f.write(env_local_content)
            print(f"[+] Saved credentials to {os.path.abspath(p)}")
        except Exception as e:
            print(f"[-] Could not write to {p}: {e}")


if __name__ == "__main__":
    asyncio.run(main())
